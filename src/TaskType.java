/**
 * Defines the category of academic work required for a task.
 */
public enum TaskType {
    /**
     * Standard homework, reading reflections, or practice exercises.
     */
    ASSIGNMENT,

    /**
     * Short diagnostic tests.
     */
    QUIZ,

    /**
     * Long-term course assignments, software prototypes, or layout designs.
     */
    PROJECT,

    /**
     * Major midterms or final evaluation tests.
     */
    EXAM,

    /**
     * Short in-class labs or worksheets.
     */
    ACTIVITY,

    /**
     * Assigned textbook chapters or source readings.
     */
    READING,

    /**
     * Academic milestones or schedule deadlines.
     */
    EVENT
}
